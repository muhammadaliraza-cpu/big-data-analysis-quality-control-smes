import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, LabelEncoder
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense

df = pd.read_excel("/content/REWORKwith_Defect_IDs.xlsx")

df['Decision'] = np.where(
    (df['Defect Level Encoded'].isin([1, 2])) |
    (df['Rework_Cost_Sum'] <= 60) |
    (df['Rework_Time_Sum'] <= 12),
    'Rework',
    'Reject'
)

label_encoder = LabelEncoder()
df['Decision_Encoded'] = label_encoder.fit_transform(df['Decision'])  # Rework = 1, Reject = 0


X = df[['Defect Level Encoded', 'Rework_Cost_Sum', 'Rework_Time_Sum']]
y = df['Decision_Encoded']

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)


X_train, X_test, y_train, y_test = train_test_split(X_scaled, y, test_size=0.2, random_state=42)

model = Sequential([
    Dense(16, input_dim=3, activation='relu'),
    Dense(8, activation='relu'),
    Dense(1, activation='sigmoid')
])

model.compile(optimizer='adam', loss='binary_crossentropy', metrics=['accuracy'])

model.fit(X_train, y_train, epochs=50, batch_size=8, validation_data=(X_test, y_test))

loss, accuracy = model.evaluate(X_test, y_test)
print(f"Test Accuracy: {accuracy:.4f}")

# Save the DataFrame with Decision columns to a new Excel file
output_file = "REWORK_Processed_with_Decision.xlsx"
df.to_excel(output_file, index=False)

print(f"\n File saved as: {output_file}")

