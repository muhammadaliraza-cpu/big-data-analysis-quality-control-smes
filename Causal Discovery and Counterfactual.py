    log_reg = LogisticRegression(max_iter=1000)
    log_reg.fit(X, treatment)
    propensity_scores = log_reg.predict_proba(X)[:, 1]

    treated_idx = df_clean[treatment == 1].index
    control_idx = df_clean[treatment == 0].index
    treated_ps = propensity_scores[treated_idx]
    control_ps = propensity_scores[control_idx]

    nn = NearestNeighbors(n_neighbors=1)
