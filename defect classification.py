import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from itertools import product

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, LabelEncoder, OneHotEncoder
from sklearn.compose import ColumnTransformer

from keras.models import Sequential
from keras.layers import Dense, Input, Activation
from keras.utils import set_random_seed

set_random_seed(42)
dataset = pd.read_excel('/content/LAYER.xlsx')

X = dataset.iloc[:, 4:11].copy()
y = dataset.iloc[:, 11].copy()

X.dropna(inplace=True)
y = y[X.index]

if not np.array_equal(np.unique(y), [0, 1]):
    le_y = LabelEncoder()
    y = le_y.fit_transform(y)

labelencoder_X_1 = LabelEncoder()
X.iloc[:, 1] = labelencoder_X_1.fit_transform(X.iloc[:, 1].astype(str))

labelencoder_X_2 = LabelEncoder()
X.iloc[:, 2] = labelencoder_X_2.fit_transform(X.iloc[:, 2].astype(str))

ct = ColumnTransformer(
    transformers=[('onehot', OneHotEncoder(handle_unknown='ignore'), [1])],
    remainder='passthrough'
)
X = ct.fit_transform(X)
X = X[:, 1:]

x_train, x_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=9)

sc = StandardScaler()
X_train = sc.fit_transform(x_train)
X_test = sc.transform(x_test)

def create_model(input_dim, layers, activation):
    model = Sequential()
    model.add(Input(shape=(input_dim,)))
    for nodes in layers:
        model.add(Dense(nodes))
        model.add(Activation(activation))
    model.add(Dense(1, activation='sigmoid'))
    model.compile(optimizer='adam', loss='binary_crossentropy', metrics=['accuracy'])
    return model

layer_configs = [[8], [16], [32, 16], [64, 32, 16]]
activations = ['relu', 'sigmoid']
batch_sizes = [16, 32]
epochs = 50

results = []
print("\nStarting Manual Grid Search:\n")

for layers, activation, batch_size in product(layer_configs, activations, batch_sizes):
    print(f"→ Training with layers={layers}, activation={activation}, batch_size={batch_size}")

    model = create_model(input_dim=X_train.shape[1], layers=layers, activation=activation)

    history = model.fit(
        X_train, y_train,
        batch_size=batch_size,
        epochs=epochs,
        verbose=0,
        validation_split=0.2
    )

    acc = history.history['val_accuracy'][-1]
    print(f"   Validation Accuracy: {acc * 100:.2f}%\n")

    results.append((layers, activation, batch_size, acc))

results.sort(key=lambda x: x[3], reverse=True)
best = results[0]

print("Best Configuration:")
print(f"Layers: {best[0]}, Activation: {best[1]}, Batch Size: {best[2]}, Validation Accuracy: {best[3]*100:.2f}%")

import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder, StandardScaler
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense
from tensorflow.keras.utils import to_categorical

df = pd.read_excel("/content/LAYER.xlsx")

def classify_defect(row):
    major_count = sum(v >= 6 for v in row)
    if all([
        1 <= row['Broken Stitches'] <= 5,
        1 <= row['Seam Puckering'] <= 5,
        1 <= row['Thread Breakage'] <= 6,
        1 <= row['Buttonhole Defects'] <= 5,
        1 <= row['Misaligned Pockets'] <= 5,
        1 <= row['Color Bleeding'] <= 6,
        1 <= row['Zipper Defects'] <= 5,
        1 <= row['Fabric Damage'] <= 5
    ]):
        return 'Minor'
    elif major_count >= 2 or any(v >= 9 for v in row):
        return 'Major'
    else:
        return 'Moderate'

feature_cols = ['Broken Stitches', 'Seam Puckering', 'Thread Breakage',
                'Buttonhole Defects', 'Misaligned Pockets', 'Color Bleeding',
                'Zipper Defects', 'Fabric Damage']
df['Defect Level'] = df[feature_cols].apply(classify_defect, axis=1)

X = df[feature_cols]
y = LabelEncoder().fit_transform(df['Defect Level'])
y_cat = to_categorical(y)

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

X_train, X_test, y_train, y_test = train_test_split(X_scaled, y_cat, test_size=0.2, random_state=42)

model = Sequential([
    Dense(64, input_dim=8, activation='relu'),
    Dense(32, activation='relu'),
    Dense(16, activation='relu'),
    Dense(3, activation='softmax')
])

model.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])

model.fit(X_train, y_train, epochs=50, batch_size=8, validation_split=0.1)

loss, accuracy = model.evaluate(X_test, y_test)
print(f"Test Loss: {loss:.4f}, Test Accuracy: {accuracy:.4f}")

